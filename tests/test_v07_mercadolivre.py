def test_authorization_url_state_and_pkce():
    flows, creds = PendingFlows(), _creds()
    r = ML.start(flows, creds, {}, 8765)
    u = urllib.parse.urlsplit(r["url"])
    q = dict(urllib.parse.parse_qsl(u.query))
    assert u.scheme == "https" and u.netloc == "auth.mercadolivre.com.br" and u.path == "/authorization"
    assert q["response_type"] == "code" and q["client_id"] == APP_ID and q["redirect_uri"] == ML.DEFAULT_REDIRECT
    assert q["code_challenge_method"] == "S256" and len(q["code_challenge"]) == 43
    assert "client_secret" not in r["url"] and "SEGREDO" not in r["url"] and "code_verifier" not in r["url"]
    m = ML.STATE_RX.match(q["state"])
    assert m and m.group(1) == "8765" and len(m.group(2)) >= 43            # 256 bits aleatórios
    f = flows.consume(q["state"])
    expect = base64.urlsafe_b64encode(hashlib.sha256(f["verifier"].encode()).digest()).rstrip(b"=").decode()
    assert expect == q["code_challenge"]
    s2 = dict(urllib.parse.parse_qsl(urllib.parse.urlsplit(ML.start(flows, creds, {}, 8765)["url"]).query))["state"]
    assert s2 != q["state"]


