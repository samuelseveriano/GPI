def test_app_flow_end_to_end_simulated(tmp_path):
    s = Srv(tmp_path / "data")
    try:
        s.app.state.sync.creds.set("mercadolivre", {"client_id": APP_ID, "client_secret": "SEGREDO-ML"})
        s.app.state.sync.http = MLHttp()
        code, lst = s.req("/api/integrations")
        ml = {p["id"]: p for p in lst}["mercadolivre"]
        assert ml["redirect_uri"] == ML.DEFAULT_REDIRECT and ml["oauth_https_relay"]
        assert "SEGREDO" not in json.dumps(lst)
        code, r = s.req("/api/integrations/mercadolivre/oauth/start", {})
        assert code == 200 and r["modo"] == "https_relay"
        st = dict(urllib.parse.parse_qsl(urllib.parse.urlsplit(r["url"]).query))["state"]
        assert st.startswith(f"{s.port}.")
        code, page = s.req("/oauth/mercadolivre/retorno", raw=True)
        assert code == 200 and b"oauth_retorno.js" in page
        code, r = s.req("/api/oauth/mercadolivre/concluir", {"colado": f"code=TG-abc123&state={st}"})
        assert code == 200 and r["apelido"] == "LOJA_TESTE"
        code, r = s.req("/api/oauth/mercadolivre/concluir", {"code": "TG-abc123", "state": st})
        assert code == 400                                                       # reutilização recusada
        code, r = s.req("/api/integrations/mercadolivre/redirect", {"redirect_uri": "http://127.0.0.1/x"})
        assert code == 400 and "HTTPS" in r["erro"]
        code, r = s.req("/api/integrations/mercadolivre/redirect", {"redirect_uri": "https://meu-dominio.example/ml/"})
        assert code == 200
        code, lst = s.req("/api/integrations")
        assert {p["id"]: p for p in lst}["mercadolivre"]["redirect_uri"] == "https://meu-dominio.example/ml/"
        code, d = s.req("/api/integrations/mercadolivre/diagnose", {})
        assert code == 200 and d["resultado"]["estado"] == "validado"
    finally:
        s.stop()


