@pytest.mark.skipif(not shutil.which("node"), reason="Node.js indisponível")
@pytest.mark.parametrize("search,expect", [
    ("?code=TG-abc123&state=8765." + "a" * 43, "http://127.0.0.1:8765/oauth/mercadolivre/retorno#code=TG-abc123&state=8765." + "a" * 43),
    ("?code=TG-abc123&state=80." + "a" * 43, None),                 # porta privilegiada/curta recusada
    ("?code=TG-abc123&state=8765.evil.com/" + "a" * 43, None),      # tentativa de redirecionamento aberto
    ("?code=<script>&state=8765." + "a" * 43, None),
    ("?error=access_denied&error_description=negado", None),
])
def test_relay_page_logic_in_node(search, expect):
    js = (ROOT / "pages/oauth/mercadolivre/relay.js").read_text(encoding="utf-8")
    harness = """
const els = {}; const el = (id) => (els[id] = els[id] || {id, hidden: true, textContent: '', value: '', attrs: {},
  setAttribute(k, v) { this.attrs[k] = v; }, addEventListener() {}, select() {}});
global.document = { getElementById: el, execCommand: () => false };
let replaced = null;
global.window = { location: { search: %s, pathname: '/GPI/oauth/mercadolivre/', replace: (u) => { replaced = u; } } };
global.history = { replaceState() {} };
global.navigator = {};
global.setTimeout = (f) => f();
%s
console.log(JSON.stringify({ replaced, link: (els.link || {attrs: {}}).attrs.href || null, status: els.status.textContent }));
""" % (json.dumps(search), js)
    out = subprocess.run(["node", "-e", harness], capture_output=True, text=True, timeout=30)
    assert out.returncode == 0, out.stderr
    r = json.loads(out.stdout.strip().splitlines()[-1])
    assert r["replaced"] == expect and r["link"] == expect
