def test_refresh_single_use_and_concurrent():
    creds, http = _creds(), MLHttp()
    ML.store(creds, {"access_token": "APP_USR-old", "refresh_token": "TG-r0", "expires_in": 1, "user_id": 777})
    out = []
    ts = [threading.Thread(target=lambda: out.append(ML.token(http, creds))) for _ in range(6)]
    [t.start() for t in ts]
    [t.join() for t in ts]
    refreshes = [c for c in http.calls if c["form"].get("grant_type") == "refresh_token"]
    assert len(refreshes) == 1 and set(out) == {"APP_USR-tok1"}                   # uma renovação só
    assert creds.get("mercadolivre")["refresh_token"] == "TG-refresh1"            # novo refresh gravado


