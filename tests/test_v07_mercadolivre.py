def test_code_exchange_users_me_and_persistence():
    flows, creds, http = PendingFlows(), _creds(), MLHttp()
    st = dict(urllib.parse.parse_qsl(urllib.parse.urlsplit(ML.start(flows, creds, {}, 8765)["url"]).query))["state"]
    r = ML.complete(http, creds, flows, "TG-codigo123", st)
    assert r == {"ok": True, "user_id": 777, "apelido": "LOJA_TESTE", "pais": "MLB"}
    c = creds.get("mercadolivre")
    assert c["access_token"] == "APP_USR-tok1" and c["refresh_token"] == "TG-refresh1" and c["user_id"] == "777"
    tok = [x for x in http.calls if x["url"] == ML.TOKEN_URL][0]["form"]
    assert tok["grant_type"] == "authorization_code" and tok["redirect_uri"] == ML.DEFAULT_REDIRECT
    with pytest.raises(SourceError, match="expirado, já utilizado"):           # state de uso único
        ML.complete(http, creds, flows, "TG-codigo123", st)


